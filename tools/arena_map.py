"""The practice arena (data/defs/maps/arena.json): a small fenced ring of packed sand in a clearing,
for trying fights one bout at a time (``--arena``; Scenarios/Arena.cs). Not a round's map: no
buildings, no villagers.

Run ``python3 tools/arena_map.py`` after editing; edit this script, not the JSON.
"""
import json
import math
import os

W = H = 32
CX, CY = 16, 16
RING = 10.5      # the fence's radius
SAND = 9.6       # the sand floor inside it

ground, levels, features = [], [], []
for y in range(H):
    g, l, f = [], [], []
    for x in range(W):
        r = math.hypot(x + 0.5 - CX, y + 0.5 - CY)
        g.append("s" if r < SAND else "d" if r < RING + 1.2 else "g")
        l.append("0")
        if abs(r - RING) < 0.55:
            f.append("f")
        elif r > RING + 3 and (x * 7 + y * 13) % 11 == 0:
            f.append("P" if (x + y) % 3 else "B")   # a clearing in the woods
        else:
            f.append(".")
    ground.append("".join(g))
    levels.append("".join(l))
    features.append(f)

# Close every diagonal-only join, so nobody slips between two posts corner to corner.
for y in range(H - 1):
    for x in range(W):
        for dx in (-1, 1):
            if 0 <= x + dx < W and features[y][x] == "f" and features[y + 1][x + dx] == "f" \
                    and features[y][x + dx] != "f" and features[y + 1][x] != "f":
                features[y][x + dx] = "f"

# Inside the fence: the weapon rack and a few barrels and crates against it, out of the way.
features[CY - 8][CX] = "R"
for (x, y, c) in ((CX - 7, CY - 5, "u"), (CX - 7, CY - 4, "u"), (CX + 7, CY + 5, "X"), (CX + 7, CY + 4, "u")):
    features[y][x] = c
features = ["".join(row) for row in features]

arena = {
    "name": "Arena",
    "label": "The practice ring",
    "description": "A fenced ring of packed sand in a clearing: one bout at a time, to learn a fight.",
    "width": W,
    "height": H,
    "depth": 8,
    "baseZ": 2,
    "groundLegend": {"g": "Grass", "d": "Dirt", "s": "Sand"},
    "featureLegend": {"f": "Fence", "P": "Pine", "B": "Birch", "u": "Barrel", "X": "Crate", "R": "WeaponRack"},
    "center": [CX, CY],
    "ground": ground,
    "levels": levels,
    "features": features,
}

out = os.path.join(os.path.dirname(__file__), "..", "data", "defs", "maps", "arena.json")
with open(out, "w") as fh:
    fh.write("// The practice arena. Generated by tools/arena_map.py: edit the script and re-run it.\n")
    json.dump({"maps": [arena]}, fh, indent=2)
    fh.write("\n")
print(f"wrote {os.path.normpath(out)}")
